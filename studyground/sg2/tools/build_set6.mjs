/* SMEAG StudyGround — tools/build_set6.mjs : SET 6 source DOCX files -> assets/set6.js.
   The shared importer is the source of truth. Source problems stay visible in the set report;
   questions whose sentence tiles cannot form the answer key remain present but unscored. */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { sourceDirs, findSourceDocsIn } from './source_docs.mjs';
import { writeSetReport } from './set_report.mjs';

const require = createRequire(import.meta.url);
const SG2 = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DOCX = require(path.join(SG2, 'assets/docx-read.js'));
const IMPORT = require(path.join(SG2, 'assets/set-import.js'));

const SET_NO = 6;
const IMPORTED_AT = '2026-10-14T00:00:00.000Z';
const FOUND = findSourceDocsIn(sourceDirs(SG2), SET_NO);
const FILES = { questions: FOUND.questions, script: FOUND.script, answers: FOUND.answers };

async function read(name) {
  const b = fs.readFileSync(path.join(FOUND.dir, name));
  return DOCX.read(b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength));
}

function optionalJson(rel) {
  const p = path.join(SG2, rel);
  return fs.existsSync(p) ? JSON.parse(fs.readFileSync(p, 'utf8')) : undefined;
}

const questions = await read(FILES.questions);
const script = await read(FILES.script);
const answers = await read(FILES.answers);
const out = IMPORT.build({
  code: 'SET 6', questions, script, answers,
  listeningImages: optionalJson('config/set6-listening-images.json'),
  discussionImages: optionalJson('config/set6-writing-images.json'),
  strictSource: true
});
if (!out.pack) {
  out.gates.forEach((g) => console.error(g.level + ' [' + g.scope + '] ' + g.message));
  process.exit(1);
}

const pack = out.pack;
pack.importedAt = IMPORTED_AT;
if (pack.summary) pack.summary.sources = [FILES.questions, FILES.script, FILES.answers];

fs.writeFileSync(
  path.join(SG2, 'assets/set6.js'),
  '/* Generated by tools/build_set6.mjs (same code path as admin-set-import.html).\n'
    + '   Do not edit by hand — fix the document or shared importer and build again. */\n'
    + 'window.SMEAG_SET6 = ' + JSON.stringify(pack, null, 2) + ';\n\n'
    + "if (window.SG_SET_IMPORT && typeof window.SG_SET_IMPORT.withHelpers === 'function') {\n"
    + '  window.SG_SET_IMPORT.withHelpers(window.SMEAG_SET6);\n'
    + '}\n'
);

const picDir = path.join(SG2, 'media/pictures/set6');
fs.mkdirSync(picDir, { recursive: true });
let pics = 0;
for (const name of Object.keys(questions.media || {})) {
  fs.writeFileSync(path.join(picDir, name.split('/').pop()), Buffer.from(questions.media[name]));
  pics++;
}

const rep = writeSetReport({ setNo: SET_NO, sg2: SG2, out, sources: pack.summary.sources });
console.log('assets/set6.js — ' + out.stats.total + ' questions '
  + JSON.stringify(out.stats.bySection) + ', ' + pics + ' pictures');
console.log('sources: ' + FOUND.dir + '\n  ' + [FILES.questions, FILES.script, FILES.answers].join('\n  '));
console.log('report: ' + path.relative(path.dirname(path.dirname(SG2)), rep.file) + ' ' + JSON.stringify(rep.counts));
